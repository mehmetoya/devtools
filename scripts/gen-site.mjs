function syncPage(file, route) {
  let html = fs.readFileSync(file, 'utf8');
  // self-hosted fonts: drop Google Fonts links
  html = html.replace(/^[ \t]*<link[^>]+fonts\.(googleapis|gstatic)\.com[^>]*>\r?\n/gm, '');
  // absolute URLs for canonical / og:url / JSON-LD
  { // rewrite old origins in <head> only (canonical, og:url, JSON-LD); page bodies are left alone
    const end = html.indexOf('</head>');
    let headPart = html.slice(0, end);
    for (const o of PREVIOUS_ORIGINS) headPart = headPart.split(o + '/').join('/').split(o + '"').join('/"');
    html = headPart + html.slice(end);
  }
  html = html.replace(/(<link rel="canonical" href=")\/([^"]*)"/g, `$1${SITE_URL}/$2"`)
             .replace(/(<meta property="og:url"\s+content=")\/([^"]*)"/g, `$1${SITE_URL}/$2"`)
             .replace(/("(?:url|item)":\s*")\/([^"]*)"/g, `$1${SITE_URL}/$2"`)
;
  html = seoHead(html, route);
  html = html.replace(/<header id="site-header">[\s\S]*?<\/header>/, staticHeader)
             .replace(/<aside id="sidebar">[\s\S]*?<\/aside>/, staticSidebar);
  html = faqBlock(html, route);
  html = relatedBlock(html, route);
  // only touch the document <head> — page scripts may legitimately contain CSP metas in template strings
  {
    const end = html.indexOf('</head>');
    html = html.slice(0, end).replace(/^[ \t]*<meta http-equiv="Content-Security-Policy"[^>]*>\r?\n/gm, '') + html.slice(end);
  }
  // hash executable inline scripts (skip src= and JSON-LD)
  const hashes = [];
  for (const m of html.matchAll(/<script(\s[^>]*)?>([\s\S]*?)<\/script>/gi)) {
    const attrs = m[1] || '';
    if (/\ssrc=/.test(attrs) || /application\/ld\+json/.test(attrs)) continue;
    hashes.push(`'sha256-${crypto.createHash('sha256').update(m[2], 'utf8').digest('base64')}'`);
  }
  const policy = cspFor(route, hashes);
  const metaPolicy = policy.replace(/ ?frame-ancestors [^;]*;/, ''); // not allowed in <meta>
  html = html.replace(/(<meta name="viewport"[^>]*>\r?\n)/, `$1  <meta http-equiv="Content-Security-Policy" content="${metaPolicy}" />\n`);
  writeIf(route, file, html);
  return policy;
}

