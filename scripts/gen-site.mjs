// Generates index.html (home), 404.html, _headers, netlify.toml, sitemap.xml and robots.txt from the
// registry in assets/tools.js, and syncs every tool page's <head>: absolute canonical/OG URLs and a
// <meta> CSP whose script-src lists sha256 hashes of that page's inline scripts.
// Run it LAST, after scripts/json-codegen/build-gen-pages.js (it rewrites those pages' heads too).
// Usage: node scripts/gen-site.mjs .
import fs from 'node:fs';
import vm from 'node:vm';
import crypto from 'node:crypto';
import { SITE_URL, PREVIOUS_ORIGINS } from './site.mjs';

