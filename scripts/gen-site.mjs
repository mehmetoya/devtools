// ── per-page head sync + CSP ──
// script-src uses sha256 hashes of each page's inline scripts instead of 'unsafe-inline', so injected
// markup (e.g. a sanitizer bypass) cannot run handlers. Exception: html-viewer, whose sandboxed srcdoc
// preview inherits the page CSP and must run the user's own inline scripts.
const INLINE_OK = new Set(['html-viewer']);
const NETWORK_OK = new Set(['http-client']);
const cspFor = (route, hashes) => {
  const o = {
    'default-src': "'self'",
    'script-src': INLINE_OK.has(route) ? "'self' 'unsafe-inline'" : ["'self'", ...hashes].join(' '),
    'style-src': "'self' 'unsafe-inline'", 'font-src': "'self'",
    'img-src': "'self' data:", 'connect-src': NETWORK_OK.has(route) ? 'http: https:' : "'none'",
    'object-src': "'none'", 'base-uri': "'self'", 'form-action': "'self'", 'frame-ancestors': "'none'",
  };
  return Object.entries(o).map(([k, v]) => `${k} ${v}`).join('; ') + ';';
};

